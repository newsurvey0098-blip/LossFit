"""Generate the checked-in TypeScript API contract from FastAPI's OpenAPI schema."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def ts_literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def schema_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f'components["schemas"][{ts_literal(name)}]'
    for composition in ("oneOf", "anyOf"):
        if composition in schema:
            return " | ".join(f"({schema_type(item)})" for item in schema[composition]) or "never"
    if "allOf" in schema:
        return " & ".join(f"({schema_type(item)})" for item in schema["allOf"]) or "unknown"
    if "enum" in schema:
        base = " | ".join(ts_literal(value) for value in schema["enum"]) or "never"
    else:
        kind = schema.get("type")
        if kind == "string":
            base = "Blob | File" if schema.get("format") == "binary" else "string"
        elif kind in {"number", "integer"}:
            base = "number"
        elif kind == "boolean":
            base = "boolean"
        elif kind == "null":
            base = "null"
        elif kind == "array":
            base = f"Array<{schema_type(schema.get('items'))}>"
        elif kind == "object" or "properties" in schema or "additionalProperties" in schema:
            props = schema.get("properties") or {}
            required = set(schema.get("required") or [])
            members = [
                f"{ts_literal(key)}{'?' if key not in required else ''}: {schema_type(value)};"
                for key, value in props.items()
            ]
            extra = schema.get("additionalProperties")
            if extra is True:
                members.append("[key: string]: unknown;")
            elif isinstance(extra, dict):
                members.append(f"[key: string]: {schema_type(extra)};")
            base = "{ " + " ".join(members) + " }" if members else "Record<string, unknown>"
        else:
            base = "unknown"
    return f"({base}) | null" if schema.get("nullable") else base


def schema_map(parameters: list[dict[str, Any]], location: str) -> str | None:
    selected = [param for param in parameters if param.get("in") == location]
    if not selected:
        return None
    members = []
    for param in selected:
        optional = "" if param.get("required") else "?"
        members.append(f"{ts_literal(param['name'])}{optional}: {schema_type(param.get('schema'))};")
    return "{ " + " ".join(members) + " }"


def operation_type(operation: dict[str, Any]) -> str:
    fields: list[str] = []
    params = operation.get("parameters", [])
    if params:
        entries = []
        for location in ("path", "query", "header", "cookie"):
            value = schema_map(params, location)
            if value:
                entries.append(f"{location}: {value};")
        if entries:
            fields.append("parameters: { " + " ".join(entries) + " };")

    body = operation.get("requestBody")
    if body:
        content = body.get("content", {})
        media = " ".join(f"{ts_literal(kind)}: {schema_type(value.get('schema'))};" for kind, value in content.items())
        fields.append(f"requestBody: {{ {'required' if body.get('required') else 'optional'}: {str(bool(body.get('required'))).lower()}; content: {{ {media} }} }};")

    responses = []
    for status, response in operation.get("responses", {}).items():
        content = response.get("content", {})
        if content:
            media = " ".join(f"{ts_literal(kind)}: {schema_type(value.get('schema'))};" for kind, value in content.items())
            responses.append(f"{ts_literal(status)}: {{ content: {{ {media} }} }};")
        else:
            responses.append(f"{ts_literal(status)}: {{ description: {ts_literal(response.get('description', ''))} }};")
    fields.append("responses: { " + " ".join(responses) + " };")
    fields.append(f"operationId: {ts_literal(operation.get('operationId', ''))};")
    return "{ " + " ".join(fields) + " }"


def render_types(schema: dict[str, Any]) -> str:
    lines = [
        "/* Generated by scripts/generate-api-types.py from backend/app/main.py. Do not edit. */",
        "export interface components {",
        "  schemas: {",
    ]
    for name, definition in schema.get("components", {}).get("schemas", {}).items():
        lines.append(f"    {ts_literal(name)}: {schema_type(definition)};")
    lines.extend(["  };", "}", "", "export interface operations {"])
    path_ops: list[tuple[str, str, str]] = []
    for path, path_item in schema.get("paths", {}).items():
        for method, operation in path_item.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete", "options", "head"}:
                continue
            operation_id = operation.get("operationId")
            if not operation_id:
                raise ValueError(f"Missing operationId for {method.upper()} {path}")
            lines.append(f"  {ts_literal(operation_id)}: {operation_type(operation)};")
            path_ops.append((path, method.lower(), operation_id))
    lines.extend(["}", "", "export interface paths {"])
    grouped: dict[str, list[tuple[str, str]]] = {}
    for path, method, operation_id in path_ops:
        grouped.setdefault(path, []).append((method, operation_id))
    for path, methods in grouped.items():
        lines.append(f"  {ts_literal(path)}: {{")
        for method, operation_id in methods:
            lines.append(f"    {ts_literal(method)}: operations[{ts_literal(operation_id)}];")
        lines.append("  };")
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    from backend.app.main import app

    openapi = app.openapi()
    outputs = {
        ROOT / "backend" / "openapi.json": json.dumps(openapi, indent=2, ensure_ascii=False) + "\n",
        ROOT / "frontend" / "src" / "api-types.ts": render_types(openapi),
    }
    stale = []
    for target, content in outputs.items():
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(target.relative_to(ROOT).as_posix())
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Generated API contract is stale: " + ", ".join(stale), file=sys.stderr)
        print("Run python scripts/generate-api-types.py and commit the generated files.", file=sys.stderr)
        return 1
    print("OpenAPI JSON and TypeScript API types are current." if args.check else "Generated OpenAPI JSON and TypeScript API types.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
